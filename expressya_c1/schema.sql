-- ExpressYa: esquema de integración C1/C2. Tipos y restricciones son decisiones técnicas propuestas.
CREATE TABLE IF NOT EXISTS dark_store (
 id_dark_store INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre_tienda VARCHAR(100) NOT NULL,
 direccion TEXT,
 estatus_activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS producto (
 sku VARCHAR(50) PRIMARY KEY,
 nombre VARCHAR(150) NOT NULL,
 descripcion TEXT,
 precio_unitario NUMERIC(12,2) NOT NULL CHECK(precio_unitario>=0),
 activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS inventario (
 id_inventario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_dark_store INTEGER NOT NULL REFERENCES dark_store(id_dark_store),
 sku VARCHAR(50) NOT NULL REFERENCES producto(sku),
 cantidad_registrada INTEGER NOT NULL DEFAULT 0 CHECK(cantidad_registrada>=0),
 cantidad_reservada INTEGER NOT NULL DEFAULT 0 CHECK(cantidad_reservada>=0),
 disponible INTEGER GENERATED ALWAYS AS (cantidad_registrada-cantidad_reservada) STORED,
 CONSTRAINT inventario_saldo_valido CHECK(cantidad_reservada<=cantidad_registrada),
 CONSTRAINT inventario_unico UNIQUE(id_dark_store,sku)
);
CREATE TABLE IF NOT EXISTS pedido (
 id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cliente VARCHAR(100) NOT NULL,
 id_dark_store INTEGER NOT NULL REFERENCES dark_store(id_dark_store),
 estado_pedido VARCHAR(40) NOT NULL DEFAULT 'PENDIENTE_DE_PAGO',
 fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 total_pedido NUMERIC(12,2) NOT NULL CHECK(total_pedido>=0),
 clave_idempotencia VARCHAR(150) NOT NULL UNIQUE,
 -- Huella técnica para reconocer reintentos idénticos, sin guardar datos de pago.
 huella_solicitud VARCHAR(64) NOT NULL
);
CREATE TABLE IF NOT EXISTS linea_pedido (
 id_linea_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_pedido BIGINT NOT NULL REFERENCES pedido(id_pedido),
 sku VARCHAR(50) NOT NULL REFERENCES producto(sku),
 cantidad_solicitada INTEGER NOT NULL CHECK(cantidad_solicitada>0),
 cantidad_surtida INTEGER NOT NULL DEFAULT 0 CHECK(cantidad_surtida>=0),
 estado_linea VARCHAR(40) NOT NULL DEFAULT 'PENDIENTE',
 CONSTRAINT linea_surtida_valida CHECK(cantidad_surtida<=cantidad_solicitada),
 UNIQUE(id_pedido,sku)
);
CREATE TABLE IF NOT EXISTS reserva (
 id_reserva BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_linea_pedido BIGINT NOT NULL REFERENCES linea_pedido(id_linea_pedido),
 id_inventario BIGINT NOT NULL REFERENCES inventario(id_inventario),
 cantidad_reservada INTEGER NOT NULL CHECK(cantidad_reservada>0),
 estado_reserva VARCHAR(20) NOT NULL DEFAULT 'CREADA' CHECK(estado_reserva IN ('CREADA','CONFIRMADA','LIBERADA','VENCIDA')),
 fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 fecha_expiracion TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS reserva_activa_por_linea ON reserva(id_linea_pedido) WHERE estado_reserva='CREADA';
CREATE INDEX IF NOT EXISTS reserva_vencimiento ON reserva(fecha_expiracion) WHERE estado_reserva='CREADA';
CREATE TABLE IF NOT EXISTS auditoria_movimiento (
 id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_inventario BIGINT NOT NULL REFERENCES inventario(id_inventario),
 tipo_operacion VARCHAR(40) NOT NULL,
 cantidad_anterior INTEGER NOT NULL,
 cantidad_cambio INTEGER NOT NULL,
 cantidad_nueva INTEGER NOT NULL,
 motivo TEXT NOT NULL,
 usuario_responsable VARCHAR(100) NOT NULL,
 fecha_hora TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
-- Auditoría append-only: ni UPDATE ni DELETE, también desde SQL directo.
CREATE OR REPLACE FUNCTION bloquear_cambios_auditoria() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'AUDITORIA_MOVIMIENTO es append-only'; END $$;
DROP TRIGGER IF EXISTS auditoria_inmutable ON auditoria_movimiento;
CREATE TRIGGER auditoria_inmutable BEFORE UPDATE OR DELETE ON auditoria_movimiento FOR EACH ROW EXECUTE FUNCTION bloquear_cambios_auditoria();
CREATE TABLE IF NOT EXISTS discrepancia_picking (
 id_discrepancia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_linea_pedido BIGINT NOT NULL REFERENCES linea_pedido(id_linea_pedido),
 id_inventario BIGINT NOT NULL REFERENCES inventario(id_inventario),
 cantidad_sistema INTEGER NOT NULL,
 cantidad_fisica_encontrada INTEGER NOT NULL,
 diferencia INTEGER NOT NULL,
 estado_discrepancia VARCHAR(30) NOT NULL DEFAULT 'DETECTADA',
 usuario_picker VARCHAR(100) NOT NULL,
 usuario_autoriza VARCHAR(100),
 fecha_registro TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
